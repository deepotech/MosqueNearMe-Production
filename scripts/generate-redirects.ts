/**
 * ============================================================
 *  generate-redirects.ts  –  Multi-platform redirect generator
 * ============================================================
 *
 * Reads public/redirect-map.json and generates platform-specific
 * 301 redirect files for ALL major hosting providers:
 *
 *   ✓ Netlify      → public/_redirects
 *   ✓ Vercel       → vercel.json  (redirects section)
 *   ✓ Cloudflare   → public/_redirects  (same format as Netlify)
 *   ✓ nginx        → nginx-redirects.conf
 *   ✓ Apache       → public/.htaccess
 *   ✓ Static HTML  → out/mosques/[old-slug]/index.html
 *
 * USAGE:
 *   npx tsx scripts/generate-redirects.ts
 *   (or: npm run redirects:generate)
 *
 * Run this AFTER `npm run slug:generate` and before deployment.
 * ============================================================
 */

import fs from 'fs';
import path from 'path';
import { loadRedirectMap } from '../lib/slug-registry';

const BASE_URL   = 'https://mosquenearme.net';
const PUBLIC_DIR = path.join(process.cwd(), 'public');
const OUT_DIR    = path.join(process.cwd(), 'out');

async function generateRedirects() {
  console.log('');
  console.log('════════════════════════════════════════════════');
  console.log('  Multi-platform Redirect Generator');
  console.log('════════════════════════════════════════════════');
  console.log('');

  const redirectMap = loadRedirectMap();
  const redirects   = Object.entries(redirectMap.redirects);

  if (redirects.length === 0) {
    console.log('ℹ️  No redirects in redirect-map.json. Nothing to generate.');
    console.log('   Run `npm run slug:generate` first if you have slug changes.');
    return;
  }

  console.log(`  Found ${redirects.length} redirects to generate\n`);

  // ── 1. Netlify / Cloudflare Pages: public/_redirects ──────
  generateNetlify(redirects);

  // ── 2. Vercel: vercel.json ─────────────────────────────────
  generateVercel(redirects);

  // ── 3. nginx: nginx-redirects.conf ────────────────────────
  generateNginx(redirects);

  // ── 4. Apache: public/.htaccess ───────────────────────────
  generateApache(redirects);

  // ── 5. Static HTML redirect pages (for output: 'export') ──
  generateStaticHTML(redirects);

  console.log('');
  console.log('✅ All redirect files generated.');
  console.log('');
  console.log('DEPLOYMENT CHECKLIST:');
  console.log('  Netlify/Cloudflare → public/_redirects is included in your deploy');
  console.log('  Vercel             → vercel.json is at repo root');
  console.log('  nginx              → copy nginx-redirects.conf to your server config');
  console.log('  Static export      → redirect HTML pages are in out/mosques/[slug]/');
  console.log('');
}

// ─── Netlify / Cloudflare Pages format ───────────────────────
function generateNetlify(redirects: [string, string][]) {
  const lines: string[] = [
    '# Auto-generated 301 redirects – DO NOT EDIT MANUALLY',
    '# Generated by: npm run redirects:generate',
    `# Generated at: ${new Date().toISOString()}`,
    `# Total redirects: ${redirects.length}`,
    '',
    '# ── Mosque slug redirects ──────────────────────────────',
  ];

  for (const [oldSlug, newSlug] of redirects) {
    // Both with and without trailing slash for robustness
    lines.push(`/mosques/${oldSlug}    /mosques/${newSlug}/  301`);
    lines.push(`/mosques/${oldSlug}/   /mosques/${newSlug}/  301`);
  }

  // Ensure directory exists
  if (!fs.existsSync(PUBLIC_DIR)) fs.mkdirSync(PUBLIC_DIR, { recursive: true });

  const outPath = path.join(PUBLIC_DIR, '_redirects');

  // Merge with existing _redirects if present (preserve manual entries)
  let existing = '';
  if (fs.existsSync(outPath)) {
    existing = fs.readFileSync(outPath, 'utf-8');
    // Remove any previous auto-generated section
    const marker = '# Auto-generated 301 redirects';
    const idx    = existing.indexOf(marker);
    if (idx !== -1) existing = existing.substring(0, idx).trim();
    if (existing) existing += '\n\n';
  }

  fs.writeFileSync(outPath, existing + lines.join('\n') + '\n', 'utf-8');
  console.log(`  ✓ Netlify/Cloudflare: public/_redirects  (${redirects.length * 2} rules)`);
}

// ─── Vercel format ────────────────────────────────────────────
function generateVercel(redirects: [string, string][]) {
  const VERCEL_PATH = path.join(process.cwd(), 'vercel.json');

  let existing: any = {};
  if (fs.existsSync(VERCEL_PATH)) {
    try {
      existing = JSON.parse(fs.readFileSync(VERCEL_PATH, 'utf-8'));
    } catch {
      console.warn('  ⚠️  Could not parse existing vercel.json – starting fresh');
    }
  }

  // Preserve non-redirect fields, replace redirects array
  const vercelRedirects = redirects.flatMap(([oldSlug, newSlug]) => [
    { source: `/mosques/${oldSlug}`,  destination: `/mosques/${newSlug}/`, permanent: true },
    { source: `/mosques/${oldSlug}/`, destination: `/mosques/${newSlug}/`, permanent: true },
  ]);

  // Preserve any manually-written redirects (those not starting with /mosques/)
  const manualRedirects = (existing.redirects ?? []).filter(
    (r: any) => !r.source?.startsWith('/mosques/')
  );

  existing.redirects = [...manualRedirects, ...vercelRedirects];

  fs.writeFileSync(VERCEL_PATH, JSON.stringify(existing, null, 2) + '\n', 'utf-8');
  console.log(`  ✓ Vercel: vercel.json  (${vercelRedirects.length} rules)`);
}

// ─── nginx format ─────────────────────────────────────────────
function generateNginx(redirects: [string, string][]) {
  const lines: string[] = [
    '# Auto-generated nginx 301 redirects',
    '# Generated by: npm run redirects:generate',
    `# Generated at: ${new Date().toISOString()}`,
    '# Include this file inside your server {} block:',
    '#   include /path/to/nginx-redirects.conf;',
    '',
    '# ── Mosque slug redirects ──────────────────────────────',
  ];

  for (const [oldSlug, newSlug] of redirects) {
    lines.push(`rewrite ^/mosques/${oldSlug}(/?)$ /mosques/${newSlug}/ permanent;`);
  }

  const outPath = path.join(process.cwd(), 'nginx-redirects.conf');
  fs.writeFileSync(outPath, lines.join('\n') + '\n', 'utf-8');
  console.log(`  ✓ nginx: nginx-redirects.conf  (${redirects.length} rules)`);
}

// ─── Apache .htaccess format ──────────────────────────────────
function generateApache(redirects: [string, string][]) {
  const lines: string[] = [
    '# Auto-generated Apache 301 redirects',
    '# Generated by: npm run redirects:generate',
    `# Generated at: ${new Date().toISOString()}`,
    '',
    'RewriteEngine On',
    '',
    '# ── Mosque slug redirects ──────────────────────────────',
  ];

  for (const [oldSlug, newSlug] of redirects) {
    lines.push(`Redirect 301 /mosques/${oldSlug} ${BASE_URL}/mosques/${newSlug}/`);
    lines.push(`Redirect 301 /mosques/${oldSlug}/ ${BASE_URL}/mosques/${newSlug}/`);
  }

  const outPath = path.join(PUBLIC_DIR, '.htaccess');
  fs.writeFileSync(outPath, lines.join('\n') + '\n', 'utf-8');
  console.log(`  ✓ Apache: public/.htaccess  (${redirects.length * 2} rules)`);
}

// ─── Static HTML redirect pages ───────────────────────────────
// For sites using `output: 'export'` where server-side redirects
// are not available. Creates a minimal HTML page with:
//   <meta http-equiv="refresh"> for immediate redirect
//   <link rel="canonical"> so Google follows the new URL
//   JavaScript fallback
function generateStaticHTML(redirects: [string, string][]) {
  // Only generate if out/ directory exists (post-build)
  if (!fs.existsSync(OUT_DIR)) {
    console.log('  ℹ️  out/ directory not found – skipping static HTML redirects');
    console.log('     Run `npm run build` first, then re-run this script');
    return;
  }

  let generated = 0;
  for (const [oldSlug, newSlug] of redirects) {
    const dir = path.join(OUT_DIR, 'mosques', oldSlug);
    if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });

    const newUrl  = `${BASE_URL}/mosques/${newSlug}/`;
    const html    = buildRedirectHTML(oldSlug, newSlug, newUrl);

    fs.writeFileSync(path.join(dir, 'index.html'), html, 'utf-8');
    generated++;
  }

  console.log(`  ✓ Static HTML: ${generated} redirect pages in out/mosques/`);
}

function buildRedirectHTML(oldSlug: string, newSlug: string, newUrl: string): string {
  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta http-equiv="refresh" content="0; url=${newUrl}">
  <link rel="canonical" href="${newUrl}">
  <title>Redirecting…</title>
  <meta name="robots" content="noindex">
  <script>
    // Immediate JS redirect as backup
    window.location.replace("${newUrl}");
  </script>
  <style>
    body { font-family: system-ui, sans-serif; display: flex; align-items: center;
           justify-content: center; min-height: 100vh; margin: 0;
           background: #f0fdf4; color: #065f46; }
    .box { text-align: center; padding: 2rem; }
    a { color: #0f4c35; font-weight: 600; }
  </style>
</head>
<body>
  <div class="box">
    <p>🕌 Redirecting to updated mosque page…</p>
    <p>If you are not redirected, <a href="${newUrl}">click here</a>.</p>
  </div>
</body>
</html>`;
}

generateRedirects().catch((err) => {
  console.error('❌ Fatal error:', err);
  process.exit(1);
});
